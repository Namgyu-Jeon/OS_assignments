// 이 파일은 프로세스 카운터의 실행 흐름을 정의합니다.
// 시작 안내, 반복 측정, ESC 종료를 ProcessMonitor 한 곳에서 관리합니다.

#pragma once

// 프로그램이 실행되는 동안 측정 시각과 프로세스 수를 1초마다 출력합니다.
// 생성할 때 받는 값은 없고, 실행 결과는 Run의 종료 코드로 알려 줍니다.
class ProcessMonitor final
{
public:
    // ESC를 누를 때까지 모니터링하며 별도의 입력값은 받지 않습니다.
    // 정상 종료는 0, 프로세스 조회나 출력 실패는 0이 아닌 값으로 돌려줍니다.
    // 오류가 생기면 같은 메시지를 계속 출력하지 않고 한 번 알린 뒤 종료합니다.
    [[nodiscard]] int Run() const;
};
